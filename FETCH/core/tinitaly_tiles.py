def tile_name(x, y):
    """Official tile name for the 50 km tile whose lower-left corner is (x, y) metres, UTM 32N."""
    n = int(round(y / 10000))
    ex = int(round(x / 10000))
    if 30 <= ex < 100:
        return f"w{n:03d}{ex:02d}"
    if ex == 100:
        return f"w{n:03d}10"
    if ex > 100:
        return f"e{n:03d}{ex - 100:02d}"
    return None  # west of x = 300 km: outside Italy
